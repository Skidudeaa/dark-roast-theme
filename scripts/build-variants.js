function relativeLuminance(value) {
  const channels = rgb(value).map((channel) => {
    const normalized = channel / 255;
    return normalized <= 0.04045 ? normalized / 12.92 : ((normalized + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2];
}

function contrast(first, second) {
  const a = relativeLuminance(first);
  const b = relativeLuminance(second);
  return Number(((Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05)).toFixed(2));
}

function colorMapFor(variant, terminal = false) {
  const map = new Map();
  for (const [name, value] of Object.entries(base.colors)) {
    if (name.startsWith('_')) continue;
    map.set(hex(value), variant.colors[name]);
  }
  for (const [name, value] of Object.entries(basePlatform)) {
    map.set(hex(value), variant.platform[name]);
  }
  // ANSI bright black is informational foreground, not a geological border.
  if (terminal) map.set(hex(base.colors.craterDeep), variant.platform.structural);
  return map;
}

function replaceHexColors(source, map) {
  return source.replace(/#([0-9a-f]{6})([0-9a-f]{2})?/gi, (match, body, alpha = '') => {
    const replacement = map.get(`#${body.toUpperCase()}`);
    return replacement ? replacement + alpha.toUpperCase() : match;
  });
}

function replaceFunctionalColors(source, map) {
  return source.replace(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)(\s*,[^)]*)?\)/gi, (match, r, g, b, tail = '') => {
    const replacement = map.get(hexFromRgb(r, g, b));
    if (!replacement) return match;
    const [nr, ng, nb] = rgb(replacement);
    return `rgb${tail ? 'a' : ''}(${nr}, ${ng}, ${nb}${tail})`;
  });
}

function replaceColors(source, map) {
  return replaceFunctionalColors(replaceHexColors(source, map), map);
}

function renameTheme(source, variant) {
  const plainName = variant.name.replace(':', '');
  return source
    .replaceAll('DARK ROAST: BLACK LABEL', variant.name.toUpperCase())
    .replaceAll('Dark Roast: Black Label', variant.name)
    .replaceAll('Dark Roast Black Label', plainName)
    .replaceAll('Black Label', variant.shortName)
    .replaceAll('BLACK LABEL', variant.shortName.toUpperCase())
    .replace('Version: 4.0.0', 'Version: 5.1.0 Companion')
    .replace('Version: 2.0 (Canonical Overhaul)', 'Version: 5.1.0 Companion')
    .replace('Version: 2.0 (Canonical)', 'Version: 5.1.0 Companion')
    .replace('Version: 2.1', 'Version: 5.1.0 Companion');
}

function namespaceKeyframes(source, variant) {
  const names = [...source.matchAll(/@keyframes\s+(dr-[\w-]+)/g)].map((match) => match[1]);
  let result = source;
  for (const name of new Set(names)) {
    const replacement = `dr-${variant.id}-${name.slice(3)}`;
    result = result.replace(
      new RegExp(`(@keyframes\\s+)${escapeRe(name)}(?=\\s*\\{)`, 'g'),
      `$1${replacement}`,
    );
    // Namespace animation identifiers without renaming the public utility
    // classes that happen to share those identifiers (for example
    // `.dr-pulse-teal`). Every family member keeps the same component API.
    result = result.replace(/animation(?:-name)?\s*:[^;}]+/g, (declaration) =>
      declaration.replace(new RegExp(`(?<![-\\w])${escapeRe(name)}(?![-\\w])`, 'g'), replacement));
  }
  return result;
}

