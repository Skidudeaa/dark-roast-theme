function nearestMappedColor(value, map, maxDelta = 3) {
  const [r, g, b] = rgb(value);
  let best = null;
  for (const [from, to] of map.entries()) {
    const [fr, fg, fb] = rgb(from);
    const delta = Math.max(Math.abs(r - fr), Math.abs(g - fg), Math.abs(b - fb));
    if (!best || delta < best.delta) best = { delta, to };
  }
  return best && best.delta <= maxDelta ? best.to : null;
}

function rewriteXcodeFloatColors(source, map) {
  return source.replace(/<string>([0-9]*\.?[0-9]+)\s+([0-9]*\.?[0-9]+)\s+([0-9]*\.?[0-9]+)\s+([0-9]*\.?[0-9]+)<\/string>/g, (match, r, g, b, a) => {
    if (Number(a) !== 1) return match;
    const current = hexFromRgb(Number(r) * 255, Number(g) * 255, Number(b) * 255);
    const replacement = map.get(current) || nearestMappedColor(current, map);
    if (!replacement) return match;
    return `<string>${rgb(replacement).map((v) => (v / 255).toFixed(3)).join(' ')} 1</string>`;
  });
}

function rewriteITermFloatColors(source, map) {
  const pattern = /(<key>Blue Component<\/key>\s*<real>)([0-9.]+)(<\/real>\s*<key>Color Space<\/key>\s*<string>[^<]+<\/string>\s*<key>Green Component<\/key>\s*<real>)([0-9.]+)(<\/real>\s*<key>Red Component<\/key>\s*<real>)([0-9.]+)(<\/real>)/g;
  return source.replace(pattern, (match, p1, b, p2, g, p3, r, p4) => {
    const current = hexFromRgb(Number(r) * 255, Number(g) * 255, Number(b) * 255);
    const replacement = map.get(current) || nearestMappedColor(current, map);
    if (!replacement) return match;
    const [nr, ng, nb] = rgb(replacement).map((v) => (v / 255).toFixed(9));
    return `${p1}${nb}${p2}${ng}${p3}${nr}${p4}`;
  });
}

function sanitizeXmlComments(source) {
  return source.replace(/<!--([\s\S]*?)-->/g, (_, body) => `<!--${body.replaceAll('--', '—') }-->`);
}

function addXmlBanner(source) {
  return source.replace(/^(<\?xml[^>]+\?>)/, `$1\n${XML_BANNER}`);
}

function addScriptBanner(source) {
  return source.startsWith('#!') ? source.replace(/^(#![^\n]+\n)/, `$1${HASH_BANNER}\n`) : `${HASH_BANNER}\n${source}`;
}

