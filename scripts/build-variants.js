function buildCssVariant(baseCss, variant, scoped) {
  let result = replaceColors(baseCss, colorMapFor(variant));
  const [ar, ag, ab] = rgb(variant.colors.amber);
  result = result.replace(
    /(::(?:-moz-)?selection\s*\{[\s\S]*?\bbackground:\s*)rgba\([^)]+\)/g,
    `$1rgba(${ar}, ${ag}, ${ab}, 0.22)`,
  );
  result = renameTheme(result, variant);
  result = namespaceKeyframes(result, variant);
  result = normalizeCssCompanionComments(result, variant);
  if (scoped) {
    result = result.replaceAll('[data-theme="dark-roast"]', `[data-theme="${variant.selector}"]`);
    // The Black Label beachhead migration table contains fixed legacy values
    // and is documentation, not runtime CSS. Do not copy stale claims into a
    // companion stylesheet.
    result = result.replace(/\n\/\* ={20,}\n   SECTION 16:[\s\S]*$/, '\n');
  } else {
    result = result.replace(/\.dark-roast(?![\w-])/g, `.${variant.className}`);
  }
  return `${BANNER}\n${addVariantCssPolish(result, variant, scoped)}`;
}

function setJsoncValue(source, key, value) {
  const serialized = typeof value === 'string' ? `"${value}"` : JSON.stringify(value);
  const pattern = new RegExp(`("${escapeRe(key)}"\\s*:\\s*)(?:"#[0-9A-Fa-f]{6,8}"|\\{[^\\n]*\\})`);
  return source.replace(pattern, `$1${serialized}`);
}

function setNamedRule(source, namePrefix, foreground, fontStyle) {
  const nameAt = source.indexOf(`"name": "${namePrefix}`);
  if (nameAt === -1) return source;
  const end = source.indexOf('\n    },', nameAt);
  if (end === -1) return source;
  const before = source.slice(0, nameAt);
  let block = source.slice(nameAt, end);
  block = block.replace(/"foreground"\s*:\s*"#[0-9A-Fa-f]{6,8}"/, `"foreground": "${foreground}"`);
  if (fontStyle !== undefined) {
    if (/"fontStyle"\s*:/.test(block)) block = block.replace(/"fontStyle"\s*:\s*"[^"]*"/, `"fontStyle": "${fontStyle}"`);
    else block = block.replace(/("foreground"\s*:\s*"#[0-9A-Fa-f]{6,8}")/, `$1, "fontStyle": "${fontStyle}"`);
  }
  return before + block + source.slice(end);
}

function setTmThemeRule(source, namePrefix, foreground, fontStyle) {
  const nameAt = source.indexOf(`<string>${namePrefix}`);
  if (nameAt === -1) return source;
  const nextRule = source.indexOf('<key>name</key>', nameAt + namePrefix.length);
  const end = nextRule === -1 ? source.length : nextRule;
  let block = source.slice(nameAt, end);
  block = block.replace(/(<key>foreground<\/key>\s*<string>)#[0-9A-Fa-f]{6,8}(<\/string>)/, `$1${foreground}$2`);
  // The Black Label source carries hand-authored token comments on the same
  // line as foreground values. A companion can intentionally remap that role,
  // so remove the inherited annotation instead of publishing a contradiction.
  block = block.replace(/(<key>foreground<\/key>\s*<string>#[0-9A-Fa-f]{6,8}<\/string>)\s*<!--[^\n]*-->/, '$1');
  if (fontStyle !== undefined) {
    if (/<key>fontStyle<\/key>/.test(block)) {
      block = block.replace(/(<key>fontStyle<\/key>\s*<string>)[^<]*(<\/string>)/, `$1${fontStyle}$2`);
    }
  }
  return source.slice(0, nameAt) + block + source.slice(end);
}

